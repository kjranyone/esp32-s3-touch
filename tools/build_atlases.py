"""Slice ImageGen 6x6 atlases and build palette sprites + animated QA previews.

python tools/build_atlases.py (Pillow required)
One shared crop/scale per character preserves animation volume and registration.
"""
from pathlib import Path
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZES = dict(lumi=96, mira=96, goro=96, slime=64, bat=64, golem=96, boss=128)


def build(name, size):
    source = Image.open(ROOT / 'assets_src' / f'{name}_atlas.png').convert('RGBA')
    frames = []
    for i in range(36):
        x, y = i % 6, i // 6
        frames.append(source.crop((round(x*source.width/6), round(y*source.height/6),
                                   round((x+1)*source.width/6), round((y+1)*source.height/6))))
    # Shared bounds; do not crop each pose independently (causes scale/anchor jitter).
    bounds = [f.getchannel('A').point(lambda a: 255 if a >= 32 else 0).getbbox() for f in frames]
    if any(b is None for b in bounds):
        raise ValueError(f'{name}: empty cell; inspect generated atlas')
    crop = (min(b[0] for b in bounds), min(b[1] for b in bounds),
            max(b[2] for b in bounds), max(b[3] for b in bounds))
    ratio = min((size-8)/(crop[2]-crop[0]), (size-8)/(crop[3]-crop[1]))
    w, h = round((crop[2]-crop[0])*ratio), round((crop[3]-crop[1])*ratio)
    normalized = []
    for frame in frames:
        canvas = Image.new('RGBA', (size, size))
        canvas.paste(frame.crop(crop).resize((w,h), Image.Resampling.LANCZOS), ((size-w)//2,size-h-3))
        normalized.append(canvas)
    strip = Image.new('RGBA', (size*6,size*6))
    for i, frame in enumerate(normalized):
        strip.paste(frame, (i%6*size,i//6*size))
    indexed = strip.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
    palette = indexed.getpalette('RGBA')
    colors, alpha = [], []
    for i in range(256):
        r,g,b,a = palette[i*4:i*4+4]
        colors.append((r>>3)<<11 | (g>>2)<<5 | b>>3)
        alpha.append(255 if a >= 240 else 0 if a <= 8 else a)
        palette[i*4+3] = alpha[-1]
    indexed.putpalette(palette, rawmode='RGBA')
    pixels = []
    for i in range(36):
        pixels.extend(indexed.crop((i%6*size,i//6*size,(i%6+1)*size,(i//6+1)*size)).getdata())
    out = ROOT/'src'/'generated'
    out.mkdir(exist_ok=True)
    lines = ['// Generated by tools/build_atlases.py', '#pragma once', '#include <stdint.h>', 'namespace sprites {',
             f'constexpr int {name}_size = {size};']
    for label, values, ctype in [('colors',colors,'uint16_t'),('alpha',alpha,'uint8_t'),('frames',pixels,'uint8_t')]:
        lines.append(f'static const {ctype} {name}_{label}[] = {{')
        lines.extend('    '+','.join(map(str,values[i:i+32]))+',' for i in range(0,len(values),32))
        lines.append('};')
    lines.append('}')
    # Row spans let the device memcpy opaque interiors instead of palette lookups
    # and alpha blending every pixel. Keep fractional alpha only on edge spans.
    spans, offsets = [], [0]
    for frame in range(36):
        for y in range(size):
            x = 0
            while x < size:
                idx = pixels[frame*size*size+y*size+x]
                if alpha[idx] == 0:
                    x += 1
                    continue
                start = x
                opaque = alpha[idx] == 255
                run = []
                while x < size:
                    idx = pixels[frame*size*size+y*size+x]
                    if not alpha[idx] or (alpha[idx] == 255) != opaque:
                        break
                    run.append(colors[idx])
                    if not opaque:
                        run.append(alpha[idx])
                    x += 1
                spans.extend([y,start,x-start,255 if opaque else 0]+run)
        offsets.append(len(spans))
    lines.pop()
    for label, values, ctype in [('spans',spans,'uint16_t'),('offsets',offsets,'uint32_t')]:
        lines.append(f'static const {ctype} {name}_{label}[] = {{')
        lines.extend('    '+','.join(map(str,values[i:i+32]))+',' for i in range(0,len(values),32))
        lines.append('};')
    lines.append('}')
    (out/f'{name}_atlas.h').write_text('\n'.join(lines)+'\n')
    previews = ROOT/'assets_src'/'previews'
    previews.mkdir(exist_ok=True)
    runtime = indexed.convert('RGBA')
    runtime.save(previews/f'{name}_contact.png')
    normalized = [runtime.crop((i%6*size,i//6*size,(i%6+1)*size,(i//6+1)*size)) for i in range(36)]
    # Preview on game-like backdrop; GIF alpha is only 1-bit.
    def gif(sequence, suffix):
        views=[]
        for i in sequence:
            bg=Image.new('RGBA',(size,size),(24,28,56,255))
            bg.alpha_composite(normalized[i])
            views.append(bg.convert('RGB').resize((size*3,size*3),Image.Resampling.NEAREST))
        views[0].save(previews/f'{name}_{suffix}.gif',save_all=True,append_images=views[1:],duration=83,loop=0)
    gif(range(4,12),'walk')
    gif(list(range(12,18 if name=='lumi' else 20))+[0,0,0],'attack')
    return dict(name=name,frames=36,size=size,crop=crop,bytes=len(spans)*2+len(offsets)*4)


if __name__=='__main__':
    results=[build(n,s) for n,s in SIZES.items()]
    (ROOT/'assets_src'/'atlas_manifest.json').write_text(json.dumps(results,indent=2)+'\n')
    print(json.dumps(results,indent=2))
