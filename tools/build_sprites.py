"""Build runtime RGB565 + alpha sprites from ImageGen source PNGs.

Run: python tools/build_sprites.py
Requires Pillow. Sources remain untouched; generated headers are committed.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def build(name, height=96):
    image = Image.open(ROOT / 'assets_src' / f'{name}.png').convert('RGBA')
    bounds = image.getchannel('A').getbbox()
    if bounds is None:
        raise ValueError(f'{name}: empty alpha')
    image = image.crop(bounds)
    image.thumbnail((112, height), Image.Resampling.LANCZOS)
    w, h = image.size
    pixels, alpha = [], []
    for r, g, b, a in image.getdata():
        pixels.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
        alpha.append(a)
    out = ROOT / 'src' / 'generated'
    out.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by tools/build_sprites.py; do not edit.', '#pragma once',
             '#include <stdint.h>', 'namespace sprites {',
             f'constexpr int {name}_w = {w}, {name}_h = {h};']
    for kind, values, ctype in [('pixels', pixels, 'uint16_t'), ('alpha', alpha, 'uint8_t')]:
        lines.append(f'static const {ctype} {name}_{kind}[] = {{')
        for i in range(0, len(values), 16):
            lines.append('    ' + ','.join(str(v) for v in values[i:i+16]) + ',')
        lines.append('};')
    lines.append('}')
    (out / f'{name}.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    image.save(out / f'{name}_preview.png')
    print(f'{name}: {w}x{h}, {w*h*3} bytes (RGB565 + alpha)')


if __name__ == '__main__':
    for name in ('lumi_idle', 'lumi_atk1'):
        build(name)
